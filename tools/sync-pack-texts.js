#!/usr/bin/env node

'use strict';

// Copies the texts that the mission speaks as free text (checklist rows, dispatch descriptions) into the base pack, voicepacks/EN.xml.
//   node tools/sync-pack-texts.js [--mission <path of tools/voice-texts.json of the mission>] [--pack voicepacks/EN.xml] [--check] [--no-bump]
// The mission lists them (node tools/voice-texts.js sync in the mission repository) as key -> English text. Here each one becomes
// <message key="CHK.x.01" text="1"><o>English</o></message> between the markers MISSION TEXTS BEGIN / END, which this tool rewrites completely.
// The messages with text="1" have one option and no actor or radio: the mission decides who speaks and how; the pack only replaces the English words
// (<text:KEY>English in the mission). The version of the pack goes up by one when the block changes (--no-bump keeps it). --check changes nothing and
// exits with 1 when the pack is not in step with the mission. See docs/architecture/VOICEPACKS.md, "Texts of the mission".
const fs = require('fs');
const path = require('path');

function arg(name, dflt) {
  const i = process.argv.indexOf('--' + name);
  return i >= 0 && i + 1 < process.argv.length ? process.argv[i + 1] : dflt;
}
const root = path.resolve(__dirname, '..');
const missionPath = path.resolve(arg('mission', path.join(root, '..', 'progetto hems', 'tools', 'voice-texts.json')));
const packPath = path.resolve(root, arg('pack', 'voicepacks/EN.xml'));
const checkOnly = process.argv.includes('--check');
const noBump = process.argv.includes('--no-bump');

const BEGIN = '  <!-- MISSION TEXTS BEGIN: generated by node tools/sync-pack-texts.js from the mission tools/voice-texts.json. Do not edit this block by hand: translate it in your own pack. -->';
const END = '  <!-- MISSION TEXTS END -->';

if (!fs.existsSync(missionPath)) { console.error('The mission file was not found: ' + missionPath + '\nUse --mission <path of tools/voice-texts.json>.'); process.exit(2); }
const texts = JSON.parse(fs.readFileSync(missionPath, 'utf8')).texts;
if (!texts || typeof texts !== 'object') { console.error('The mission file has no "texts".'); process.exit(2); }

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function describe(key) {
  if (key.startsWith('CHK.')) return { actor: 11, trigger: 'checklist ' + key.split('.')[1] };
  if (key === 'DSC.VEH') return { actor: 8, trigger: 'dispatch: the vehicle of the search missions (values {0} colour, {1} model)' };
  if (key.startsWith('DSC.')) return { actor: 8, trigger: 'dispatch description of incident ' + key.split('.')[1] + ', variant ' + key.split('.')[2] };
  return { actor: 1, trigger: '' };
}
const lines = [BEGIN];
for (const [key, text] of Object.entries(texts)) {
  if (/[^\x20-\x7e]/.test(text)) { console.error('The text of ' + key + ' is not ASCII.'); process.exit(2); }
  const d = describe(key);
  lines.push(`    <message key="${key}" text="1" actor="${d.actor}" trigger="${escape(d.trigger).replace(/"/g, '&quot;')}">`);
  lines.push(`      <o>${escape(text)}</o>`);
  lines.push('    </message>');
}
lines.push(END);
const block = lines.join('\n');

let xml = fs.readFileSync(packPath, 'utf8');
const eol = xml.includes('\r\n') ? '\r\n' : '\n';
xml = xml.replace(/\r\n/g, '\n');
const bi = xml.indexOf(BEGIN.slice(0, 40));
const ei = xml.indexOf(END);
let next;
if (bi >= 0 && ei > bi) next = xml.slice(0, bi) + block + xml.slice(ei + END.length);
else if (bi >= 0 || ei >= 0) { console.error('The markers of the block are damaged in ' + packPath); process.exit(2); }
else next = xml.replace(/<\/voicepack>\s*$/, block + '\n</voicepack>\n');
const changed = next !== xml;
if (checkOnly) {
  console.log(changed ? 'pack texts: EN.xml is NOT in step with the mission texts (run node tools/sync-pack-texts.js)' : 'pack texts: PASS (' + Object.keys(texts).length + ' texts)');
  process.exit(changed ? 1 : 0);
}
if (!changed) { console.log('pack texts: nothing to do (' + Object.keys(texts).length + ' texts)'); process.exit(0); }
if (!noBump) {
  next = next.replace(/(<voicepack\b[^>]*\bversion=")(\d+)(")/, (all, a, v, c) => { console.log('pack version ' + v + ' -> ' + (parseInt(v, 10) + 1)); return a + (parseInt(v, 10) + 1) + c; });
}
fs.writeFileSync(packPath, next.replace(/\n/g, eol), 'utf8');
console.log('pack texts: ' + Object.keys(texts).length + ' texts written to ' + path.relative(root, packPath));
